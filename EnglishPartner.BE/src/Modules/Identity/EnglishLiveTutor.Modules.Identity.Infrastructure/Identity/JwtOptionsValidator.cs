using System.Text;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Options;

namespace EnglishLiveTutor.Infrastructure.Identity;

public sealed class JwtOptionsValidator : IValidateOptions<JwtOptions>
{
    private readonly IHostEnvironment? _environment;

    public JwtOptionsValidator(IHostEnvironment? environment = null)
    {
        _environment = environment;
    }

    public ValidateOptionsResult Validate(string? name, JwtOptions options)
    {
        bool isDevelopment = _environment?.IsDevelopment() ?? false;

        if (string.IsNullOrWhiteSpace(options.SecretKey))
        {
            if (isDevelopment)
            {
                // In Development, an ephemeral key will be generated by HmacJwtTokenService
                return ValidateOptionsResult.Success;
            }

            return ValidateOptionsResult.Fail(
                "Jwt:SecretKey configuration is required in non-Development environments. Please configure the 'Jwt:SecretKey' setting.");
        }

        if (Encoding.UTF8.GetByteCount(options.SecretKey) < 32)
        {
            return ValidateOptionsResult.Fail(
                $"Jwt:SecretKey must be at least 32 bytes (256 bits) long. Current key length is {Encoding.UTF8.GetByteCount(options.SecretKey)} bytes. Please configure 'Jwt:SecretKey'.");
        }

        return ValidateOptionsResult.Success;
    }
}
